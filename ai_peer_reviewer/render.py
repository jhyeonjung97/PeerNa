def render_html(
    result: ReviewResult, manuscript_name: str, mode: str, model_label: str
) -> str:
    report = result.report
    e = html.escape
    out: list[str] = []

    title = f"Referee report — {manuscript_name}"

    out.append("<!doctype html>")
    out.append('<html lang="en"><head><meta charset="utf-8">')
    out.append('<meta name="viewport" content="width=device-width, initial-scale=1">')
    out.append(f"<title>{e(title)}</title>")
    out.append(f"<style>:root{{--watermark:{_logo_data_uri()};}}{STYLES}</style>")
    out.append("</head><body><main>")

    out.append('<div class="watermark" aria-hidden="true"></div>')
    out.append(f"<header><h1>{e(title)}</h1>")
    out.append(f'<p class="wordmark">{_logo()}<span>PeerNa</span></p>')
    out.append("</header>")

    call = RECOMMENDATION_LABELS.get(report.recommendation, report.recommendation)
    out.append(f'<p class="verdict">Recommendation: <strong>{e(call)}</strong></p>')
    out.append(f'<p class="general">{e(report.general_comments.strip())}</p>')

    out.append('<ol class="comments">')
    for comment in report.comments:
        out.append(f'<li class="{comment.severity}">{e(comment.text.strip())}</li>')
    out.append("</ol>")

    out.append('<section class="appendix">')
    out.append("<h2>Citations checked</h2>")
    out.append(f'<p class="note">{e(_coverage_line(report))}</p>')
    if report.citation_checks:
        for check in report.citation_checks:
            label = STATUS_LABELS.get(check.status, check.status)
            out.append(
                f'<div class="citation">'
                f'<span class="tag {check.status}">{e(label)}</span> '
                f'<span class="ref">{e(check.reference)}</span> '
                f'<span class="note">— {e(check.location)}</span>'
            )
            if check.note.strip():
                out.append(f'<p class="note">{e(check.note.strip())}</p>')
            out.append("</div>")

    out.append(
        f'<p class="verdictLine">Reviewer confidence: {e(report.confidence)}</p>'
    )

    if result.warnings:
        out.append("<h2>Run warnings</h2><ul>")
        out.extend(f"<li>{e(w)}</li>" for w in dict.fromkeys(result.warnings))
        out.append("</ul>")

    out.append(f'<p class="disclosure">{e(AI_DISCLOSURE)} Model: {e(model_label)}.</p>')
    sources = _credit_sources(result)
    if sources:
        out.append(f'<p class="disclosure">{e(PRECEDENT_CREDIT)}</p>')
        out.append('<ul class="credit">')
        for line in sources:
            out.append(f"<li>{e(line)}</li>")
        out.append("</ul>")
    out.append("</section>")
    out.append("</main></body></html>")
    return "\n".join(out)


def _credit_sources(result: ReviewResult) -> list[str]:
    raw = result.pass_notes.get("precedent_sources") or ""
    return [line.strip() for line in raw.splitlines() if line.strip()]


def _credit_lines(result: ReviewResult) -> list[str]:
    sources = _credit_sources(result)
    if not sources:
        return []
    return ["", f"_{PRECEDENT_CREDIT}_", ""] + [f"- {s}" for s in sources] + [""]


def _coverage_line(report: RefereeReport) -> str:
    """Say how much of the bibliography was examined.

    Without this the list reads as the whole story. It is not: absence from a
    list of eight checked citations says nothing about the other fifty.
    """
    checked = len(report.citation_checks)
    total = report.references_total
    if not checked:
        return (
            "No citation was verified in this run."
            + (f" The manuscript lists about {total} references." if total else "")
        )
    if total and total >= checked:
        return (
            f"{checked} of about {total} references were examined. The rest were "
            "not looked at — absence from this list is not evidence that a "
            "citation is sound."
        )
    return (
        f"{checked} reference(s) were examined. The rest of the bibliography was "
        "not looked at."
    )
