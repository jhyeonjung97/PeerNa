"""Render a structured review into a referee report.

Two output formats from the same structure: Markdown for pasting into a journal
submission form, and a self-contained HTML page for reading and printing. The
HTML embeds everything — no network requests — because these reports describe
unpublished manuscripts and should not reach for anything outside the file.
"""

from __future__ import annotations

import html
import urllib.parse
from functools import lru_cache
from pathlib import Path

from .review import ReviewResult
from .schema import RefereeReport

LOGO_PATH = Path(__file__).parent / "web" / "logo.svg"

#: Ink for the watermark. A CSS background image cannot inherit currentColor, so
#: the mark behind the page needs a colour of its own — mid grey reads the same
#: against the light page and the dark one at the opacity it is drawn at.
WATERMARK_INK = "#8a827a"


@lru_cache(maxsize=None)
def _logo(colour: str | None = None) -> str:
    """The PeerNa mark. Inline when it inherits the page ink, otherwise recoloured."""
    svg = LOGO_PATH.read_text(encoding="utf-8").strip()
    return svg if colour is None else svg.replace("currentColor", colour)


def _logo_data_uri() -> str:
    return "url(\"data:image/svg+xml," + urllib.parse.quote(_logo(WATERMARK_INK)) + "\")"


RECOMMENDATION_LABELS = {
    "accept": "Accept",
    "minor_revision": "Minor revision",
    "major_revision": "Major revision",
    "reject": "Reject",
}

STATUS_LABELS = {
    "verified": "verified",
    "not_found": "NOT FOUND",
    "misattributed": "MISATTRIBUTED",
    "unverified": "unverified",
}

#: The corpus this tool consults is the transparent peer review Nature
#: Communications publishes, and each of those files carries CC BY 4.0 — which
#: permits this use outright and asks in return that the source be credited.
#: The referees are anonymous, so what gets credited is the paper and the
#: journal. Nothing of theirs is reproduced: the passes are told to take the
#: expectation and leave the sentence.
PRECEDENT_CREDIT = (
    "Field expectations were drawn from the referee reports published with the "
    "papers below, under CC BY 4.0 "
    "(https://creativecommons.org/licenses/by/4.0/). Nothing from them is "
    "reproduced here."
)

AI_DISCLOSURE = (
    "Generated by an AI peer review tool. Every point should be checked against "
    "the manuscript before being acted on or sent to anyone."
)


def render(result: ReviewResult, manuscript_name: str, mode: str, model_label: str) -> str:
    """A referee report: one opening paragraph, then a numbered list.

    Deliberately plain. Real reports have no section headings, no strengths
    list, no severity labels — adding them would make the output easy to spot as
    machine-written and harder to paste into a journal's form.
    """
    report = result.report
    lines: list[str] = []

    call = RECOMMENDATION_LABELS.get(report.recommendation, report.recommendation)
    lines += [
        f"**{manuscript_name}**",
        "",
        f"**Recommendation: {call}**",
        "",
        report.general_comments.strip(),
        "",
    ]

    for index, comment in enumerate(report.comments, start=1):
        lines += [f"{index}. {comment.text.strip()}", ""]

    lines += _appendix_lines(report, result, model_label)
    return "\n".join(lines)


def _appendix_lines(report: RefereeReport, result: ReviewResult, model_label: str) -> list[str]:
    """Citation checks, then the run's own metadata.

    Citations get their own heading rather than being folded into the numbered
    comments: a referee does not normally audit a bibliography, so presenting it
    as part of the review would misrepresent what it is, and burying it as a
    footnote would waste the one thing here a human reviewer rarely does.
    """
    lines = ["---", "", "**Citations checked**", "", _coverage_line(report), ""]
    if report.citation_checks:
        for check in report.citation_checks:
            status = STATUS_LABELS.get(check.status, check.status)
            entry = f"- **[{status}]** {check.reference} — {check.location}"
            if check.note.strip():
                entry += f"\n  - {check.note.strip()}"
            lines.append(entry)
        lines.append("")
    lines += [
        f"_Reviewer confidence: {report.confidence}._",
        "",
        f"_{AI_DISCLOSURE} Model: {model_label}._",
        "",
    ]
    lines += _credit_lines(result)
    if result.warnings:
        lines += ["", "**Run warnings**", ""]
        lines += [f"- {w}" for w in dict.fromkeys(result.warnings)]
        lines.append("")
    return lines


def render_pass_notes(result: ReviewResult) -> str:
    """The raw per-pass findings, for when the synthesis drops something."""
    from .passes import PASSES

    lines = ["# Per-pass notes", ""]
    if result.pass_notes.get("precedent"):
        lines += [
            "## What referees expect of papers like this",
            "",
            f"_Sources: {result.pass_notes.get('precedent_sources', '')}_",
            "",
            result.pass_notes["precedent"],
            "",
        ]
    for review_pass in PASSES:
        lines += [
            f"## {review_pass.title}",
            "",
            result.pass_notes.get(review_pass.key, "(no findings)"),
            "",
        ]
    return "\n".join(lines)


